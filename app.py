def get_game_latest_news(game_name):
    game_clean = game_name.lower()
    if "gta" in game_clean or "grand theft auto 6" in game_clean:
        return "Actualité : Rockstar Games a confirmé une mise à jour majeure du moteur physique pour fin 2026."
    elif "elden ring" in game_clean:
        return "Actualité : Des rumeurs circulent sur un second DLC, mais FromSoftware se concentre sur une nouvelle IP en 2026."
    return f"Recherche web effectuée pour '{game_name}' : Le jeu est activement suivi par la communauté, aucune anomalie majeure signalée récemment."

def calculate_pc_bottleneck(cpu, gpu):
    if "i3" in cpu.lower() and "rtx 4090" in gpu.lower():
        return "Résultat du calcul : Bottleneck SEVÈRE (environ 45%). Le processeur limite grandement la carte graphique."
    return "Résultat du calcul : Configuration équilibrée (Bottleneck inférieur à 8%). Les composants fonctionnent de manière optimale."

